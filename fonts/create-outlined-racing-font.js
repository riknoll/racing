#!/usr/bin/env node
const fs = require("node:fs")
const path = require("node:path")

const root = path.resolve(__dirname, "..")
const output = path.join(__dirname, "racing-outlined.g.ts")

function generate() {
    const source = fs.readFileSync(path.join(root, "pxt_modules/racing (font)/main.ts"), "utf8")
    const match = source.match(/export const racing\b[^=]*=\s*new fancyText\.Font\(hex`([\da-f\s]+)`\)/i)
    if (!match) throw new Error("Cannot find the racing font buffer")
    const font = Buffer.from(match[1].replace(/\s/g, ""), "hex")
    if (font.readUInt32LE(0) !== 0x68f119dc) throw new Error("Expected a single-tone V2 racing font")
    if (font[6] > 253 || font[7] > 254 || font[9] > 253) throw new Error("Font metrics are too large to outline")
    const count = font.readUInt16LE(4)
    const bitmapStart = 13 + count * 4
    const table = Buffer.alloc(count * 4)
    const glyphs = []
    let offset = 0
    let maxBitmapLength = 0

    for (let i = 0; i < count; i++) {
        const entry = 13 + i * 4
        const start = bitmapStart + font.readUInt16LE(entry + 2)
        const width = font[start + 1]
        const height = font[start + 2]
        if (font[start] > 253 || width > 253 || height > 253 || font.readInt8(start + 4) === -128) {
            throw new Error(`Glyph ${font.readUInt16LE(entry)} is too large to outline`)
        }
        const kernLength = font[start + 5] * 3
        const pixels = start + 6 + kernLength
        const byteHeight = Math.ceil(height / 8)
        const outlinedWidth = width + 2
        const outlinedHeight = height + 2
        const outlinedByteHeight = Math.ceil(outlinedHeight / 8)
        const bitmapLength = outlinedWidth * outlinedByteHeight
        const outline = Buffer.alloc(bitmapLength)
        const fill = Buffer.alloc(bitmapLength)
        for (let x = 0; x < width; x++) {
            for (let y = 0; y < height; y++) {
                if (!(font[pixels + x * byteHeight + (y >> 3)] & (1 << (y & 7)))) continue
                fill[(x + 1) * outlinedByteHeight + ((y + 1) >> 3)] |= 1 << ((y + 1) & 7)
                for (let dx = 0; dx <= 2; dx++) {
                    for (let dy = 0; dy <= 2; dy++) {
                        outline[(x + dx) * outlinedByteHeight + ((y + dy) >> 3)] |= 1 << ((y + dy) & 7)
                    }
                }
            }
        }
        const header = Buffer.from(font.subarray(start, start + 6))
        header[0] += 2
        header[1] = outlinedWidth
        header[2] = outlinedHeight
        header.writeInt8(font.readInt8(start + 4) - 1, 4)
        table.writeUInt16LE(font.readUInt16LE(entry), i * 4)
        table.writeUInt16LE(offset, i * 4 + 2)
        const glyph = Buffer.concat([header, font.subarray(start + 6, pixels), outline, fill])
        glyphs.push(glyph)
        offset += glyph.length
        maxBitmapLength = Math.max(maxBitmapLength, bitmapLength)
    }

    const header = Buffer.from(font.subarray(0, 13))
    header.writeUInt32LE(0x68f119dd, 0)
    header[6] += 2
    header[7] += 1
    header[9] += 2
    header.writeUInt16LE(maxBitmapLength, 11)
    const hex = Buffer.concat([header, table, ...glyphs]).toString("hex").match(/.{1,96}/g).join("\n        ")
    return `// Generated by node fonts/create-outlined-racing-font.js. Do not edit.
namespace racing {
    //% whenUsed
    export const outlinedRacingFont: fancyText.BaseFont = new fancyText.Font(hex\`
        ${hex}
    \`);
}
`
}

if (require.main === module) {
    try {
        const args = process.argv.slice(2)
        if (args.some(arg => arg !== "--check")) throw new Error("Usage: node fonts/create-outlined-racing-font.js [--check]")
        const content = generate()
        if (args.includes("--check")) {
            if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== content) {
                throw new Error("Outlined font is stale; run node fonts/create-outlined-racing-font.js")
            }
        } else fs.writeFileSync(output, content)
        console.log(args.includes("--check") ? "Outlined racing font is up to date" : "Generated fonts/racing-outlined.g.ts")
    } catch (error) {
        console.error(`create-outlined-racing-font.js: ${error.message}`)
        process.exitCode = 1
    }
}

module.exports = { generate }
